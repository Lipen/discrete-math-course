//! Атака Полига--Хеллмана на DLOG (глава m13, раздел «Взлом»).
//!
//! Если порядок группы $p - 1$ гладкий, дискретный логарифм сводится
//! к логарифмам в подгруппах малых порядков и собирается по CRT.
//! Для $p = 29$ порядок $28 = 2^2 dot 7$ --- гладкий, и логарифм
//! находится практически мгновенно.

use crypto::attacks::pohlig_hellman;
use crypto::mod_pow;

fn main() {
    let p = 29;
    let g = 2; // образующий ZZ_29^*
    let x = 13;
    let h = mod_pow(g, x, p);

    println!("Порядок группы p - 1 = {} = 2^2 * 7 (гладкий)", p - 1);
    println!("Ищем x в g^x = {h} (mod {p}), где g = {g}");

    let recovered = pohlig_hellman(p, g, h).expect("гладкий порядок --- атака обязана удаться");
    println!("Полиг--Хеллман нашёл x = {recovered}");
    println!(
        "Вот почему порядок выбирают с большим простым делителем (безопасное простое p - 1 = 2q)."
    );
}
